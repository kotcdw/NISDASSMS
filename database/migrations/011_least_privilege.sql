ALTER TABLE users
    ADD COLUMN totp_secret VARCHAR(255) NULL AFTER password_hash,
    ADD COLUMN totp_enabled_at DATETIME NULL AFTER totp_secret,
    ADD COLUMN totp_last_step BIGINT UNSIGNED NOT NULL DEFAULT 0 AFTER totp_enabled_at,
    ADD COLUMN recovery_codes TEXT NULL AFTER totp_last_step,
    ADD COLUMN password_changed_at DATETIME NULL AFTER recovery_codes,
    ADD COLUMN locked_reason VARCHAR(255) NULL AFTER is_active;

UPDATE users SET password_changed_at = COALESCE(updated_at, created_at) WHERE must_change_password = 0;

CREATE TABLE IF NOT EXISTS password_history (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    user_id INT UNSIGNED NOT NULL,
    hash VARCHAR(255) NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_ph_user (user_id, id),
    CONSTRAINT fk_pwhist_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS user_sessions (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    user_id INT UNSIGNED NOT NULL,
    token_hash CHAR(64) NOT NULL UNIQUE,
    ip VARCHAR(45) NULL,
    user_agent VARCHAR(255) NULL,
    mfa TINYINT(1) NOT NULL DEFAULT 0,
    created_at DATETIME NOT NULL,
    last_seen_at DATETIME NOT NULL,
    revoked_at DATETIME NULL,
    revoked_reason VARCHAR(30) NULL,
    INDEX idx_us_user (user_id, revoked_at),
    CONSTRAINT fk_usess_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

