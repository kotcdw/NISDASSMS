-- NISDAS SMS — Sprint 13: least privilege & role-based access control, editable by the Super Admin
--  * roles + role_permissions (seeded with exactly the rules used until now, plus "Health & special needs")
--  * custom roles (based on a built-in role), data scope (all classes / own classes), per-role sign-in rules
--  * 2-step sign-in (authenticator app), password history and expiry, tracked sessions

CREATE TABLE IF NOT EXISTS roles (
    role_key VARCHAR(40) NOT NULL PRIMARY KEY,
    name VARCHAR(80) NOT NULL,
    description VARCHAR(255) NULL,
    base_role VARCHAR(40) NULL,
    kind ENUM('staff','parent','pupil') NOT NULL DEFAULT 'staff',
    is_system TINYINT(1) NOT NULL DEFAULT 0,
    data_scope ENUM('all','own') NOT NULL DEFAULT 'all',
    require_2fa TINYINT(1) NOT NULL DEFAULT 0,
    idle_minutes SMALLINT UNSIGNED NOT NULL DEFAULT 30,
    allowed_days VARCHAR(20) NULL,
    allowed_from TIME NULL,
    allowed_to TIME NULL,
    allowed_networks VARCHAR(500) NULL,
    sort_order SMALLINT NOT NULL DEFAULT 50,
    is_active TINYINT(1) NOT NULL DEFAULT 1,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NULL ON UPDATE CURRENT_TIMESTAMP,
    updated_by INT UNSIGNED NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

